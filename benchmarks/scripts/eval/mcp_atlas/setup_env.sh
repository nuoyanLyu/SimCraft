#!/usr/bin/env bash
# Write mcp-atlas/.env for evaluating the EnvFactory model.
#   - model under test  -> local vLLM OpenAI endpoint (LiteLLM "openai/<served>")
#   - LLM-as-judge       -> dmxapi DeepSeek-V3.2 (EnvFactory paper setting)
# The dmxapi key is reused from EnvFactory/.env EMBEDDING_API_KEY.
#
# Server selection (must be set BEFORE `make run-docker`, the sandbox reads it at startup):
#   MCP_SERVERS_MODE=default    (default) ENABLED_SERVERS empty -> 20 no-key servers + auto-detect
#   MCP_SERVERS_MODE=envfactory  EnvFactory paper Appendix F: the 30 servers (36 minus the 6
#                                excluded: mongodb, oxylabs, brave-search, wikipedia, slack,
#                                google-workspace). Key-gated servers among the 30 still need
#                                their keys added below to actually start.
set -euo pipefail
EF_ROOT="/home/lvnuoyan/EnvFactory"
ATLAS_DIR="/data1/lvnuoyan/dataset/agent/mcp-atlas"

DMX_KEY="$(grep -E '^EMBEDDING_API_KEY=' "$EF_ROOT/.env" | cut -d= -f2-)"
LLM_BASE_URL="${LLM_BASE_URL:-http://localhost:8100}"
MCP_SERVERS_MODE="${MCP_SERVERS_MODE:-default}"

# EnvFactory paper subset: all 36 servers minus the 6 excluded = 30.
EF_30_SERVERS="airtable,alchemy,arxiv,calculator,cli-mcp-server,clinicaltrialsgov-mcp-server,context7,ddg-search,desktop-commander,e2b-server,exa,fetch,filesystem,git,github,google-maps,lara-translate,mcp-code-executor,mcp-server-code-runner,memory,met-museum,national-parks,notion,open-library,osm-mcp-server,pubmed,twelvedata,weather,weather-data,whois"

# Servers the user cannot provision (wallet/billing-gated: no API key). Removed from
# the enabled set AND from the task subset. Override via USER_EXCLUDE_SERVERS=... or "".
USER_EXCLUDE_SERVERS="${USER_EXCLUDE_SERVERS-lara-translate,google-maps}"
EF_SERVERS="$(python3 -c "import sys; excl=set(x for x in sys.argv[2].split(\",\") if x); print(\",\".join(s for s in sys.argv[1].split(\",\") if s not in excl))" "$EF_30_SERVERS" "$USER_EXCLUDE_SERVERS")"
EF_N="$(python3 -c "import sys; print(len(sys.argv[1].split(\",\")))" "$EF_SERVERS")"

if [ "$MCP_SERVERS_MODE" = "envfactory" ]; then
    ENABLED_SERVERS_LINE="ENABLED_SERVERS=${EF_SERVERS}"
    SERVERS_NOTE="envfactory (${EF_N} servers, paper subset minus [${USER_EXCLUDE_SERVERS}])"
else
    ENABLED_SERVERS_LINE="ENABLED_SERVERS="
    SERVERS_NOTE="default (20 no-key + auto-detect)"
fi

cat > "$ATLAS_DIR/.env" << ENVEOF
# Auto-generated by scripts/eval/mcp_atlas/setup_env.sh -- do not hand-edit.
${ENABLED_SERVERS_LINE}

# --- Model under evaluation: local vLLM (served-model-name = envfactory-eval) ---
LLM_API_KEY=EMPTY
LLM_BASE_URL=${LLM_BASE_URL}
MCP_SANDBOX_URL=http://localhost:1984

# Slow thinking model: give it room.
LLM_TIMEOUT_MS=600000
LIST_TOOLS_TIMEOUT_MS=180000
TOOL_CALL_TIMEOUT_MS=120000

# --- LLM-as-judge: dmxapi DeepSeek-V3.2 ---
EVAL_LLM_MODEL=DeepSeek-V3.2
EVAL_LLM_API_KEY=${DMX_KEY}
EVAL_LLM_BASE_URL=https://www.dmxapi.cn
ENVEOF

# Merge user-maintained server API keys (keys.env, gitignored) so they survive
# regeneration. Copy keys.env.template -> keys.env and fill in what you have.
KEYS_FILE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/keys.env"
if [ -f "$KEYS_FILE" ]; then
    {
        echo ""
        echo "# --- merged from keys.env ---"
        grep -E '^[A-Z][A-Z0-9_]*=' "$KEYS_FILE"
    } >> "$ATLAS_DIR/.env"
    NKEYS="$(grep -cE '^[A-Z][A-Z0-9_]*=.+' "$KEYS_FILE" || true)"
    echo "[setup_env] merged $NKEYS non-empty key(s) from keys.env"
fi

echo "[setup_env] wrote $ATLAS_DIR/.env (servers=$SERVERS_NOTE, LLM_BASE_URL=$LLM_BASE_URL, judge=DeepSeek-V3.2@dmxapi)"
